// 各 L3 項目（バング・カニンガム等）の「③ 適合の軸」は、
// 必ずここで定義した 5 変数のいずれかに紐づける。

export type GlossaryDirection = "受ける" | "逃がす" | "中立";

export interface GlossaryTerm {
  /** URLアンカー & React key に使う */
  id: "power" | "twist" | "draft-position" | "angle-of-attack" | "sea-state";
  /** 表示名（日本語） */
  label: string;
  /** 英語の併記（任意） */
  labelEn?: string;
  /** 1行で本質を伝えるサマリー */
  oneLiner: string;
  /** 何を見て判断するか */
  observe: string[];
  /** 「過剰／受けすぎ」のときに起きること */
  whenExcess: { signs: string[]; action: string };
  /** 「不足／逃がしすぎ」のときに起きること */
  whenLack: { signs: string[]; action: string };
  /** この変数を動かす主なコントロール（後で個別ページにリンク） */
  controlledBy: string[];
  /** タクミの判断手順（3ステップ程度） */
  judgement: string[];
}

